-- ------------------------------------------------------------
-- Los valores controlados se implementan con CHECK para aceptar
-- parámetros de texto sin conversiones explícitas.

-- ------------------------------------------------------------
-- Usuarios y roles
-- ------------------------------------------------------------
CREATE TABLE users (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                VARCHAR(120)  NOT NULL,
  email               VARCHAR(190)  NOT NULL UNIQUE,
  password_hash       VARCHAR(255)  NOT NULL,
  role               VARCHAR(10)   NOT NULL DEFAULT 'user'
                     CONSTRAINT chk_users_role CHECK (role IN ('admin', 'user')),
  token_limit_month   INTEGER       NOT NULL DEFAULT 50000
                      CONSTRAINT chk_users_token_limit CHECK (token_limit_month >= 0),
  active              BOOLEAN       NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_role_active ON users (role, active);

-- ------------------------------------------------------------
-- Catálogo turístico
-- ------------------------------------------------------------
CREATE TABLE destinations (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(150)  NOT NULL,
  region       VARCHAR(120)  NOT NULL,
  description  TEXT          NOT NULL,
  category     VARCHAR(80)   NOT NULL,
  tags         VARCHAR(255)  NULL,
  lat          NUMERIC(10, 7) NULL,
  lng          NUMERIC(10, 7) NULL,
  price_level  SMALLINT      NOT NULL DEFAULT 2
               CONSTRAINT chk_destinations_price_level
               CHECK (price_level BETWEEN 1 AND 4),
  best_season  VARCHAR(100)  NULL,
  active       BOOLEAN       NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_destinations_name_region UNIQUE (name, region)
);

CREATE INDEX idx_destinations_region ON destinations (region);
CREATE INDEX idx_destinations_category ON destinations (category);
CREATE INDEX idx_destinations_active ON destinations (active);

CREATE TABLE activities (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destination_id  BIGINT        NOT NULL REFERENCES destinations (id)
                  ON DELETE CASCADE ON UPDATE CASCADE,
  name            VARCHAR(180)  NOT NULL,
  description     TEXT          NOT NULL,
  category        VARCHAR(80)   NOT NULL,
  duration_min    INTEGER       NOT NULL DEFAULT 0
                  CONSTRAINT chk_activities_duration CHECK (duration_min >= 0),
  price           NUMERIC(12, 2) NOT NULL DEFAULT 0
                  CONSTRAINT chk_activities_price CHECK (price >= 0),
  lat             NUMERIC(10, 7) NULL,
  lng             NUMERIC(10, 7) NULL,
  active          BOOLEAN       NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_activities_destination_name UNIQUE (destination_id, name)
);

CREATE INDEX idx_activities_destination ON activities (destination_id);
CREATE INDEX idx_activities_category ON activities (category);
CREATE INDEX idx_activities_active ON activities (active);

-- ------------------------------------------------------------
-- Documentos para el RAG (fuente de recuperación)
-- La columna search_vector reemplaza al índice FULLTEXT de MySQL;
-- se mantiene con un trigger y se consulta con tsquery en español.
-- ------------------------------------------------------------
CREATE TABLE documents (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_type  VARCHAR(40)   NOT NULL,
  source_id    BIGINT        NULL,
  chunk_index  INTEGER       NOT NULL DEFAULT 0,
  title        VARCHAR(200)  NOT NULL,
  content      TEXT          NOT NULL,
  url          VARCHAR(500)  NULL,
  metadata     JSONB         NULL,
  search_vector TSVECTOR     NULL,
  created_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_documents_source UNIQUE (source_type, source_id, chunk_index)
);

CREATE INDEX idx_documents_source ON documents (source_type, source_id);
CREATE INDEX idx_documents_search ON documents USING GIN (search_vector);

CREATE OR REPLACE FUNCTION documents_search_vector_update()
RETURNS trigger AS $$
BEGIN
  NEW.search_vector :=
    setweight(to_tsvector('spanish', coalesce(NEW.title, '')), 'A') ||
    setweight(to_tsvector('spanish', coalesce(NEW.content, '')), 'B');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_documents_search_vector
BEFORE INSERT OR UPDATE OF title, content ON documents
FOR EACH ROW EXECUTE FUNCTION documents_search_vector_update();

-- ------------------------------------------------------------
-- Servicios de IA configurables
-- ------------------------------------------------------------
CREATE TABLE ai_services (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(60)   NOT NULL UNIQUE,
  name          VARCHAR(120)  NOT NULL,
  description   TEXT          NOT NULL,
  model         VARCHAR(120)  NOT NULL DEFAULT 'openai/gpt-oss-120b',
  temperature   NUMERIC(3, 2) NOT NULL DEFAULT 0.20,
  max_tokens    INTEGER       NOT NULL DEFAULT 1024,
  system_prompt TEXT          NOT NULL,
  enabled       BOOLEAN       NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_services_enabled ON ai_services (enabled);

-- ------------------------------------------------------------
-- Conversaciones e historial
-- ------------------------------------------------------------
CREATE TABLE conversations (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         BIGINT        NOT NULL REFERENCES users (id)
                  ON DELETE CASCADE ON UPDATE CASCADE,
  service_code    VARCHAR(60)   NOT NULL REFERENCES ai_services (code)
                  ON DELETE RESTRICT ON UPDATE CASCADE,
  title           VARCHAR(200)  NULL,
  summary         TEXT          NULL,
  last_message_at TIMESTAMPTZ   NULL DEFAULT NULL,
  created_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_conversations_user ON conversations (user_id, last_message_at);
CREATE INDEX idx_conversations_service ON conversations (service_code);

CREATE TABLE messages (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id  BIGINT        NOT NULL REFERENCES conversations (id)
                   ON DELETE CASCADE ON UPDATE CASCADE,
  role             VARCHAR(10)   NOT NULL
                   CONSTRAINT chk_messages_role
                   CHECK (role IN ('system', 'user', 'assistant', 'tool')),
  content          TEXT          NOT NULL,
  sources_json     JSONB         NULL,
  tokens_in        INTEGER       NOT NULL DEFAULT 0,
  tokens_out       INTEGER       NOT NULL DEFAULT 0,
  created_at       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_messages_conversation ON messages (conversation_id, id);

-- ------------------------------------------------------------
-- Consumo de tokens (tabla de hechos para analítica)
-- ------------------------------------------------------------
CREATE TABLE usage_logs (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            BIGINT        NOT NULL REFERENCES users (id)
                     ON DELETE RESTRICT ON UPDATE CASCADE,
  service_code       VARCHAR(60)   NOT NULL REFERENCES ai_services (code)
                     ON DELETE RESTRICT ON UPDATE CASCADE,
  conversation_id    BIGINT        NULL REFERENCES conversations (id)
                     ON DELETE SET NULL ON UPDATE CASCADE,
  message_id         BIGINT        NULL REFERENCES messages (id)
                     ON DELETE SET NULL ON UPDATE CASCADE,
  model              VARCHAR(120)  NOT NULL,
  prompt_tokens      INTEGER       NOT NULL DEFAULT 0,
  completion_tokens  INTEGER       NOT NULL DEFAULT 0,
  total_tokens       INTEGER       NOT NULL DEFAULT 0,
  latency_ms         INTEGER       NULL,
  status             VARCHAR(10)   NOT NULL DEFAULT 'success'
                     CONSTRAINT chk_usage_status
                     CHECK (status IN ('success', 'error', 'blocked')),
  error_code         VARCHAR(60)   NULL,
  created_at         TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_usage_user_date ON usage_logs (user_id, created_at);
CREATE INDEX idx_usage_service_date ON usage_logs (service_code, created_at);
CREATE INDEX idx_usage_date ON usage_logs (created_at);

-- ------------------------------------------------------------
-- Ejecuciones de agentes multi-paso
-- ------------------------------------------------------------
CREATE TABLE agent_runs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT           NOT NULL REFERENCES users (id)
                ON DELETE CASCADE ON UPDATE CASCADE,
  service_code  VARCHAR(60)      NOT NULL REFERENCES ai_services (code)
                ON DELETE RESTRICT ON UPDATE CASCADE,
  input_json    JSONB            NOT NULL,
  output_json   JSONB            NULL,
  steps_json    JSONB            NULL,
  status        VARCHAR(10)    NOT NULL DEFAULT 'success'
                CONSTRAINT chk_agent_runs_status
                CHECK (status IN ('running', 'success', 'error', 'partial')),
  total_tokens  INTEGER          NOT NULL DEFAULT 0,
  latency_ms    INTEGER          NULL,
  created_at    TIMESTAMPTZ      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_agent_runs_user_date ON agent_runs (user_id, created_at);
CREATE INDEX idx_agent_runs_service_date ON agent_runs (service_code, created_at);

-- ------------------------------------------------------------
-- Consumidores externos (Power BI, Postman)
-- ------------------------------------------------------------
CREATE TABLE api_clients (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(120)  NOT NULL,
  key_hash     CHAR(64)      NOT NULL UNIQUE,
  key_prefix   VARCHAR(20)   NOT NULL,
  scope        VARCHAR(120)  NOT NULL DEFAULT 'analytics:read',
  active       BOOLEAN       NOT NULL DEFAULT TRUE,
  last_used_at TIMESTAMPTZ   NULL DEFAULT NULL,
  created_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_api_clients_active ON api_clients (active);

-- ------------------------------------------------------------
-- Caché de respuestas externas (Open-Meteo, OSRM, Wikipedia)
-- ------------------------------------------------------------
CREATE TABLE external_cache (
  cache_key   VARCHAR(191)  PRIMARY KEY,
  payload     TEXT          NOT NULL,
  expires_at  TIMESTAMPTZ   NOT NULL,
  created_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_external_cache_expires ON external_cache (expires_at);

-- ------------------------------------------------------------
-- Vistas de apoyo para el reporte web y Power BI
-- ------------------------------------------------------------
CREATE VIEW v_usage_daily AS
SELECT
  (created_at AT TIME ZONE 'UTC')::date AS usage_date,
  service_code,
  user_id,
  COUNT(*)                              AS requests,
  COALESCE(SUM(prompt_tokens), 0)       AS prompt_tokens,
  COALESCE(SUM(completion_tokens), 0)   AS completion_tokens,
  COALESCE(SUM(total_tokens), 0)        AS total_tokens
FROM usage_logs
WHERE status = 'success'
GROUP BY (created_at AT TIME ZONE 'UTC')::date, service_code, user_id;

CREATE VIEW v_usage_by_service AS
SELECT
  service_code,
  COUNT(*)                              AS requests,
  COALESCE(SUM(prompt_tokens), 0)       AS prompt_tokens,
  COALESCE(SUM(completion_tokens), 0)   AS completion_tokens,
  COALESCE(SUM(total_tokens), 0)        AS total_tokens
FROM usage_logs
WHERE status = 'success'
GROUP BY service_code;

-- ------------------------------------------------------------
-- Trigger genérico de updated_at
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users', 'destinations', 'activities', 'documents', 'ai_services',
    'conversations'
  ]
  LOOP
    EXECUTE format(
      'CREATE TRIGGER trg_%s_updated_at BEFORE UPDATE ON %I
       FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      t, t
    );
  END LOOP;
END;
$$;
